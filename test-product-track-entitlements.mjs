import assert from "node:assert/strict";
import {isProductUnlocked,entitledProducts,trackCovered} from "./src/product-entitlements.js";
const date="2026-11-24";
const p=(id,category,track,race_date=date,price_cents=999)=>({id,category,track,race_date,price_cents});
const a=p("a","Race Cards","Turf Paradise"),b=p("b","Race Cards","Mountaineer"),c=p("c","Pick Tickets","Turf Paradise"),d=p("d","Race Cards","Turf Paradise","2026-11-25"),f=p("f","Longshot Radar",""),g=p("g","Race Cards","");
const scope=x=>({product_id:x.id,category:x.category,race_date:x.race_date,track:x.track,expires_at:Date.now()+100000});
const access={universal:false,scopes:[scope(a)]};
assert.deepEqual(entitledProducts([a,b,c,d],access),[a]);
assert.deepEqual(entitledProducts([a,b,c],{universal:false,scopes:[scope(a),scope(b)]}),[a,b]);
assert.equal(isProductUnlocked({...a,track:b.track},access),false);
assert.equal(isProductUnlocked({...a,id:"other"},access),false);
assert.equal(isProductUnlocked(a,{universal:false,scopes:[{...scope(a),expires_at:0}]}),false);
assert.equal(isProductUnlocked(b,{universal:false,scopes:[]}),false);
assert.equal(isProductUnlocked({...b,price_cents:0},{universal:false,scopes:[]}),true);
assert.equal(isProductUnlocked(b,{universal:true,scopes:[]}),true);
assert.equal(trackCovered([a],"Race Cards","Turf Paradise"),true);
assert.equal(trackCovered([a],"Race Cards"," turf paradise "),true);
assert.equal(trackCovered([a],"Race Cards","Turf"),false);
assert.equal(trackCovered([a],"Race Cards","Mountaineer"),false);
assert.equal(trackCovered([g],"Race Cards","Turf Paradise"),false);
assert.equal(trackCovered([f],"Longshot Radar","Mountaineer"),true);
assert.equal(trackCovered([p("x","Target List","Turf Paradise")],"Target List","Mountaineer"),false);
console.log("PASS: track-specific purchase, bundle, membership, free and expired access");
